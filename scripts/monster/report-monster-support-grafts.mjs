import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterSupportGraftCatalogAudit } from "../../features/monster-composer/model/monster-support-graft.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase6");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "support-grafts.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "support-grafts.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderCountTable(values = {}) {
  return Object.entries(values)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `| ${key} | ${value} |`)
    .join("\n");
}

function renderMarkdown(audit) {
  const rows = audit.reports.map((report) => {
    const bands = report.scaling.declared
      ? `${report.scaling.bandCount} (${report.scaling.sampledBandIds.join(" → ")})`
      : "static";
    return `| ${report.source} | ${report.slot} | \`${report.id}\` | ${report.kind} | ${report.counterplayChannels.join(", ")} | ${bands} | ${report.parityStatuses.join(", ")} | ${report.status} |`;
  });

  return `# Terrifying Monsters — Phase 6 Support Graft Audit

**Generated by:** \`scripts/monster/report-monster-support-grafts.mjs\`  
**Audit version:** \`${audit.version}\`

## Summary

| Metric | Value |
|---|---:|
| Non-Attack Graft v2 | ${audit.total} |
| Passing | ${audit.passing} |
| Errors | ${audit.error} |
| Catalog errors | ${audit.errors.length} |
| CR-scaled support grafts | ${audit.scaled} |
| Verified parity | ${audit.verifiedParity} |
| Candidate parity | ${audit.candidateParity} |

## Distribution by slot

| Slot | Count |
|---|---:|
${renderCountTable(audit.bySlot)}

## Distribution by source

| Source | Count |
|---|---:|
${renderCountTable(audit.bySource)}

## Catalog

CR scaling is sampled at CR 1, 5, 10, and 15. A declared progression must compile successfully and produce at least two distinct rule variants.

| Source | Slot | Graft | Kind | Counterplay channels | CR progression | Parity | Status |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## Gate

The audit fails unless all 75 non-Attack grafts use the Graft v2 contract, compile at every checkpoint, expose identity and at least two counterplay channels, provide explicit balance/complexity/spike profiles, and preserve verified rule-render parity.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath)
      ? fs.readFileSync(filePath, "utf8")
      : null;
    if (actual !== content) {
      console.error(
        `Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`,
      );
      return false;
    }
    return true;
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterSupportGraftCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(
  `Support grafts: ${audit.total}; passing: ${audit.passing}; scaled: ${audit.scaled}; verified parity: ${audit.verifiedParity}; errors: ${audit.errors.length}.`,
);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
