import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterMindGraftEditorialCatalogAudit } from "../../features/monster-composer/model/monster-mind-graft.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase6r");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "mind-grafts.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "mind-grafts.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderCountTable(values = {}) {
  return Object.entries(values)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `| ${key} | ${value} |`)
    .join("\n");
}

function renderMarkdown(audit) {
  const rows = audit.reports.map((report) => {
    const scaling = report.scaling.declared
      ? `${report.scaling.bandCount} bands (${report.scaling.sampledBandIds.join(" → ")})`
      : "Static";
    return `| ${report.source} | \`${report.id}\` | ${report.title} | ${report.decision} | ${report.abilityCount} | ${scaling} | ${report.counterplayChannels.join(", ")} | ${report.status} |`;
  });

  return `# Terrifying Monsters — Phase 6R Mind Editorial Audit

**Generated by:** \`scripts/monster/report-monster-mind-editorial.mjs\`  
**Audit version:** \`${audit.version}\`  
**Editorial version:** \`${audit.editorialVersion}\`

## Summary

| Metric | Value |
|---|---:|
| Mind Grafts reviewed | ${audit.total}/${audit.expectedTotal} |
| Passing | ${audit.passing} |
| Warnings | ${audit.warning} |
| Errors | ${audit.error} |
| Authored abilities | ${audit.abilityCount} |
| Multi-ability bundles | ${audit.bundleCount} |
| CR-scaled Mind Grafts | ${audit.scaledCount} |
| Catalog errors | ${audit.errors.length} |

## Editorial decisions

| Decision | Count |
|---|---:|
${renderCountTable(audit.byDecision)}

## Distribution by source

| Source | Count |
|---|---:|
${renderCountTable(audit.bySource)}

## Catalog

| Source | ID | Published title | Decision | Abilities | CR model | Counterplay channels | Status |
|---|---|---|---|---:|---|---|---|
${rows.join("\n")}

## Publication gate

The Mind family passes only when all eleven catalog entries:

- have an approved editorial decision and rationale;
- define a recognizable behavioral fantasy and tactical role;
- compile as Grafts with verified structured-rule parity;
- expose all four counterplay channels;
- preserve explicit Monster Frame fit and a concrete behavioral routine;
- compile cleanly at CR 1, 5, 10, and 15;
- produce distinct rule variants whenever CR scaling is declared.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath)
      ? fs.readFileSync(filePath, "utf8")
      : null;
    if (actual !== content) {
      console.error(
        `Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`,
      );
      return false;
    }
    return true;
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterMindGraftEditorialCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(
  `Mind Grafts: ${audit.total}; passing: ${audit.passing}; abilities: ${audit.abilityCount}; bundles: ${audit.bundleCount}; scaled: ${audit.scaledCount}; errors: ${audit.errors.length}.`,
);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
