import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { renderStructuredRulesText } from "../../features/monster-composer/model/monster-graft-rules.render.js";
import { summarizeMonsterRulesParity } from "../../features/monster-composer/model/monster-rules-parity.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIRECTORY = path.join(
  REPO_ROOT,
  "docs/terrifying-monsters/phase3",
);
const OUTPUT_JSON = path.join(OUTPUT_DIRECTORY, "rules-parity.generated.json");
const OUTPUT_MARKDOWN = path.join(
  OUTPUT_DIRECTORY,
  "rules-parity.generated.md",
);
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");
const REQUIRED_VERIFIED_IDS = Object.freeze([
  "slam-decomposition:heavy-slam",
  "skin-slippage:body-trait",
]);

const computed = Object.freeze({
  attack: 6,
  dc: 13,
  dpr: 20,
  targetCr: 2,
  category: "Zombie",
  categoryNoun: "zombie",
  rulesContext: { categoryNoun: "zombie" },
});

function render(feature) {
  return renderStructuredRulesText(feature, computed) || "";
}

function getParityFeatures(grafts = []) {
  return grafts.flatMap((graft) => {
    if (!Array.isArray(graft.abilities) || !graft.abilities.length) {
      return [graft];
    }
    return graft.abilities.map((ability) => ({
      ...ability,
      id: `${graft.id}:${ability.id}`,
      source: graft.source,
      sourceAnchors: graft.sourceAnchors,
      slot: graft.slot,
      cost: graft.cost,
      complexity: graft.complexity,
    }));
  });
}

function renderMarkdown(summary) {
  const verifiedRows = summary.reports.filter((report) => report.applicable);
  const rows = verifiedRows.length
    ? verifiedRows
        .map(
          (report) =>
            `| \`${report.featureId}\` | ${report.pass ? "Pass" : "Fail"} | ${report.effectCount} | ${report.conditionalDamageCount} | ${report.errors} | ${report.warnings} |`,
        )
        .join("\n")
    : "| — | — | 0 | 0 | 0 | 0 |";
  const failures = verifiedRows
    .filter((report) => !report.pass)
    .flatMap((report) =>
      report.issues.map(
        (issue) =>
          `- \`${report.featureId}\` / \`${issue.code}\`: ${issue.message}`,
      ),
    );

  return `# Terrifying Monsters — Phase 3 Rules Parity Report

**Generated by:** \`scripts/monster/report-monster-rules-parity.mjs\`

## Contract

A graft may declare \`rules.parity.status = "verified"\` only when:

1. every player-facing mechanical clause has a structured representation;
2. every balance-relevant clause has an explicit simulation disposition;
3. conditional damage contributes to the three-round profile through an expected activation rate;
4. the final structured renderer contains every verified clause.

## Summary

| Metric | Value |
|---|---:|
| Authored ability rules | ${summary.total} |
| Verified ability rules | ${summary.verified} |
| Passed | ${summary.passed} |
| Failed | ${summary.failed} |
| Structured effect clauses | ${summary.effects} |
| Conditional damage clauses | ${summary.conditionalDamage} |

## Verified grafts

| Graft | Result | Effects | Conditional damage | Errors | Warnings |
|---|---|---:|---:|---:|---:|
${rows}

## Failures

${failures.length ? failures.join("\n") : "No verified parity failures."}

## Required Phase 3 pilot coverage

${REQUIRED_VERIFIED_IDS.map((id) => `- \`${id}\``).join("\n")}
`;
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function assertCurrent(filePath, expected) {
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing generated parity report: ${path.relative(REPO_ROOT, filePath)}`);
  }
  const current = fs.readFileSync(filePath, "utf8");
  if (current !== expected) {
    throw new Error(`Generated parity report is stale: ${path.relative(REPO_ROOT, filePath)}`);
  }
}

const parityFeatures = getParityFeatures(MONSTER_GRAFTS);
const summary = summarizeMonsterRulesParity(parityFeatures, { render });
const requiredReports = REQUIRED_VERIFIED_IDS.map((id) =>
  summary.reports.find((report) => report.featureId === id),
);
const missingRequired = REQUIRED_VERIFIED_IDS.filter(
  (id, index) => !requiredReports[index]?.applicable,
);
const failingRequired = requiredReports.filter(
  (report) => report?.applicable && !report.pass,
);
const json = stableJson(summary);
const markdown = renderMarkdown(summary);

if (CHECK_MODE) {
  assertCurrent(OUTPUT_JSON, json);
  assertCurrent(OUTPUT_MARKDOWN, markdown);
} else {
  fs.mkdirSync(OUTPUT_DIRECTORY, { recursive: true });
  fs.writeFileSync(OUTPUT_JSON, json);
  fs.writeFileSync(OUTPUT_MARKDOWN, markdown);
}

console.log(
  `[monster-rules-parity] total=${summary.total} verified=${summary.verified} passed=${summary.passed} failed=${summary.failed}`,
);

if (missingRequired.length) {
  console.error(
    `[monster-rules-parity] required pilot grafts are not verified: ${missingRequired.join(", ")}`,
  );
}
if (failingRequired.length) {
  console.error(
    `[monster-rules-parity] required pilot grafts failed: ${failingRequired.map((report) => report.featureId).join(", ")}`,
  );
}

if (
  STRICT_MODE &&
  (summary.failed > 0 || missingRequired.length > 0 || failingRequired.length > 0)
) {
  process.exitCode = 1;
}
