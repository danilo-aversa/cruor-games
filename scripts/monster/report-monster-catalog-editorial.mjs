import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterCatalogEditorialAudit } from "../../features/monster-composer/model/monster-catalog-editorial.js";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase8");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "catalog-editorial.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "catalog-editorial.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function tableRows(values = {}) {
  return Object.entries(values)
    .map(([key, value]) => `| ${key} | ${value} |`)
    .join("\n");
}

function renderMarkdown(audit) {
  const longFormRows = audit.styleReview.longFormAbilities.length
    ? audit.styleReview.longFormAbilities
        .map((entry) => `| \`${entry.graftId}\` | ${entry.title} | ${entry.wordCount} | ${entry.rationale} |`)
        .join("\n")
    : "| — | — | — | None |";
  const sharedRows = audit.crossReview.sharedAbilityGroups.length
    ? audit.crossReview.sharedAbilityGroups
        .slice(0, 20)
        .map((group) => `| ${group.title} | ${group.occurrences.length} | ${group.occurrences.map((entry) => `\`${entry.graftId}:${entry.abilityId}\``).join(", ")} |`)
        .join("\n")
    : "| — | 0 | — |";
  return `# Terrifying Monsters — Phase 8 Catalog Editorial Audit

**Generated by:** \`scripts/monster/report-monster-catalog-editorial.mjs\`  
**Audit version:** \`${audit.version}\`

## Publication gate

| Metric | Value |
|---|---:|
| Published grafts | ${audit.total} |
| Cross-catalog duplicate Attack Pattern groups | ${audit.crossReview.duplicatePatternGroups.length} |
| Complexity mismatches | ${audit.crossReview.complexityMismatches.length} |
| Hard style outliers | ${audit.styleReview.hardOutliers.length} |
| Unreviewed long-form abilities | ${audit.styleReview.unreviewedLongForm.length} |
| Missing counterplay profiles | ${audit.playabilityReview.counterplayFailures.length} |
| Non-executable routines | ${audit.playabilityReview.routineFailures.length} |
| Failed CR projections | ${audit.playabilityReview.validationFailures.length} |
| Errors | ${audit.errors.length} |
| Gate | ${audit.pass ? "PASS" : "FAIL"} |

## Catalog distribution

### By slot

| Slot | Count |
|---|---:|
${tableRows(audit.bySlot)}

### By source

| Source | Count |
|---|---:|
${tableRows(audit.bySource)}

## Cross-review

- Attack Pattern fingerprints were compared at CR 5 and CR 15 after stripping migration and parity metadata.
- Shared base actions are permitted; entire parent patterns may not compile to the same mechanical bundle.
- Declared complexity may not be lower than the highest authored decision, branch, sequence, or tracking score.
- Duplicate climbing chassis and infrastructure-heavy web features must produce a soft compatibility conflict.

### Reused base abilities

| Ability | Occurrences | Parents |
|---|---:|---|
${sharedRows}

## Monster Manual style review

Calibration: ${audit.styleReview.benchmark.monsters} MM'25 monsters and ${audit.styleReview.benchmark.authoredEntries} authored entries from \`${audit.styleReview.benchmark.source}\`.

| Metric | Cruor CR 5 catalog |
|---|---:|
| Authored abilities | ${audit.styleReview.catalog.abilityCount} |
| Median words | ${audit.styleReview.catalog.medianWords} |
| Mean words | ${audit.styleReview.catalog.meanWords} |
| 75th percentile | ${audit.styleReview.catalog.p75Words} |
| 90th percentile | ${audit.styleReview.catalog.p90Words} |
| Maximum | ${audit.styleReview.catalog.maximumWords} |
| Hard limit | ${audit.styleReview.hardWordLimit} |

Cruor abilities remain intentionally more procedural than the MM'25 median, but no ability may exceed the hard limit. Text above ${audit.styleReview.reviewThreshold} words requires an explicit rationale.

### Reviewed long-form abilities

| Graft | Ability | Words | Rationale |
|---|---|---:|---|
${longFormRows}

## Playability review

- ${audit.playabilityReview.totalCompiledProjections} graft/CR projections compiled across CR 1, 5, 10, and 15.
- Every graft retains telegraph, positioning, break-condition, and non-damage counterplay channels.
- Table-facing families retain executable default procedures.
- Infrastructure-heavy web features and duplicate climbing chassis surface soft compatibility warnings instead of silently stacking tracking load.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== content) {
      console.error(`Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterCatalogEditorialAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(`Catalog: ${audit.total}; duplicate patterns: ${audit.crossReview.duplicatePatternGroups.length}; hard style outliers: ${audit.styleReview.hardOutliers.length}; compiled projections: ${audit.playabilityReview.totalCompiledProjections}; errors: ${audit.errors.length}.`);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
