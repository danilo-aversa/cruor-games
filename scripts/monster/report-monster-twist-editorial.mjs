import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterTwistGraftCatalogAudit } from "../../features/monster-composer/model/monster-twist-graft.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase6r");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "twist-grafts.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "twist-grafts.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderCountTable(values = {}) {
  return Object.entries(values)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `| ${key} | ${value} |`)
    .join("\n");
}

function renderMarkdown(audit) {
  const rows = audit.reports.map((report) => {
    const scaling = report.scaling.declared
      ? `${report.scaling.bandCount} bands (${report.scaling.sampledBandIds.join(" → ")})`
      : "Static";
    return `| ${report.source} | \`${report.id}\` | ${report.title} | ${report.decision} | ${report.abilityCount} | ${scaling} | ${report.counterplayChannels.join(", ")} | ${report.status} |`;
  });

  return `# Terrifying Monsters — Phase 6R Twist Editorial Audit

**Generated by:** \`scripts/monster/report-monster-twist-editorial.mjs\`  
**Audit version:** \`${audit.version}\`  
**Editorial version:** \`${audit.editorialVersion}\`

## Summary

| Metric | Value |
|---|---:|
| Twist Grafts reviewed | ${audit.total}/${audit.expectedTotal} |
| Passing | ${audit.passing} |
| Warnings | ${audit.warning} |
| Errors | ${audit.error} |
| Authored abilities | ${audit.abilityCount} |
| Multi-ability bundles | ${audit.bundleCount} |
| CR-scaled Twist Grafts | ${audit.scaledCount} |
| Catalog errors | ${audit.errors.length} |

## Editorial decisions

| Decision | Count |
|---|---:|
${renderCountTable(audit.byDecision)}

## Distribution by source

| Source | Count |
|---|---:|
${renderCountTable(audit.bySource)}

## Catalog

| Source | ID | Published title | Decision | Abilities | CR model | Counterplay channels | Status |
|---|---|---|---|---:|---|---|---|
${rows.join("\n")}

## Publication gate

The Twist family passes only when:

- every existing Twist ID has an explicit KEEP, REWRITE, EXPAND, RENAME, or canonical-preservation decision;
- the encounter change is visible before or when it resolves;
- random hidden d6 escalation, indefinite stacking, and automatic ambush criticals are removed;
- every Twist offers positioning, break-condition, and non-damage responses;
- canonical Bestiary names such as Undead Fortitude and Siege Monster are preserved where the feature remains recognizable;
- Twist remains distinct from Body chassis, Mind behavior, Movement routes, Horror sensory reveals, Attack routines, and Death aftermath;
- every CR projection compiles with verified renderer parity.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== content) {
      console.error(`Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterTwistGraftCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(
  `Twist Grafts: ${audit.total}; passing: ${audit.passing}; abilities: ${audit.abilityCount}; bundles: ${audit.bundleCount}; scaled: ${audit.scaledCount}; errors: ${audit.errors.length}.`,
);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
