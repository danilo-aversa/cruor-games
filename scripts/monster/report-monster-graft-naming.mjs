import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterGraftNamingCatalogAudit } from "../../features/monster-composer/model/monster-graft-naming.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase6r");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "graft-naming.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "graft-naming.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderMarkdown(audit) {
  const rows = audit.reports.map((report) => {
    const basis = report.slot === "attack"
      ? "Evocative pattern"
      : report.canonicalBestiaryName
        ? "Bestiary canonical"
        : report.approvedException
          ? "Approved signature"
          : "Editorial";
    return `| ${report.slot} | \`${report.id}\` | ${report.title} | ${report.wordCount} | ${basis} | ${report.pass ? "pass" : "error"} |`;
  });
  return `# Terrifying Monsters — Graft Naming Audit

**Generated by:** \`scripts/monster/report-monster-graft-naming.mjs\`  
**Audit version:** \`${audit.version}\`

## Naming rules

- The published name is a short UI label, not a lore subtitle.
- Attack Patterns use an evocative parent name; their individual actions retain canonical or descriptive names.
- Preserve exact D&D Bestiary feature names for Body, Mind, and Movement when the Graft remains recognizably based on that feature.
- Otherwise use one or two familiar English words.
- Do not use hyphens, em dashes, apostrophes, colons, or stacked clauses.
- Signature-action names may use an approved third word when shortening would make them less recognizable.
- Name the recognizable body, behavior, or combat identity rather than obscure implementation details.
- Keep stable internal IDs separate from published names.

## Summary

| Metric | Value |
|---|---:|
| Reviewed slots | ${audit.reviewedSlots.join(", ")} |
| Reviewed names | ${audit.total} |
| Passing | ${audit.passing} |
| Errors | ${audit.errors.length} |

## Catalog

| Slot | Stable ID | Published name | Words | Basis | Status |
|---|---|---|---:|---|---|
${rows.join("\n")}
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== content) {
      console.error(`Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterGraftNamingCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(`Graft names: ${audit.total}; passing: ${audit.passing}; errors: ${audit.errors.length}.`);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
