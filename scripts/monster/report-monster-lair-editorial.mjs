import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterLairGraftEditorialCatalogAudit } from "../../features/monster-composer/model/monster-lair-graft.js";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase6r");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "lair-grafts.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "lair-grafts.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function renderCountTable(values = {}) {
  return Object.entries(values)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `| ${key} | ${value} |`)
    .join("\n");
}

function renderMarkdown(audit) {
  const rows = audit.reports.map((report) => {
    const scaling = report.scaling.declared
      ? `${report.scaling.bandCount} bands (${report.scaling.sampledBandIds.join(" → ")})`
      : "Static";
    return `| ${report.source} | \`${report.id}\` | ${report.title} | ${report.decision} | ${report.abilityCount} | ${scaling} | ${report.counterplayChannels.join(", ")} | ${report.status} |`;
  });

  return `# Terrifying Monsters — Phase 6R Lair Editorial Audit

**Generated by:** \`scripts/monster/report-monster-lair-editorial.mjs\`  
**Audit version:** \`${audit.version}\`  
**Editorial version:** \`${audit.editorialVersion}\`

## Summary

| Metric | Value |
|---|---:|
| Lair Effects reviewed | ${audit.total}/${audit.expectedTotal} |
| Passing | ${audit.passing} |
| Warnings | ${audit.warning} |
| Errors | ${audit.error} |
| Authored abilities | ${audit.abilityCount} |
| Multi-ability bundles | ${audit.bundleCount} |
| CR-scaled Lair Effects | ${audit.scaledCount} |
| Catalog errors | ${audit.errors.length} |

## Editorial decisions

| Decision | Count |
|---|---:|
${renderCountTable(audit.byDecision)}

## Distribution by source

| Source | Count |
|---|---:|
${renderCountTable(audit.bySource)}

## Catalog

| Source | ID | Published title | Decision | Abilities | CR model | Counterplay channels | Status |
|---|---|---|---|---:|---|---|---|
${rows.join("\n")}

## Publication gate

The Lair family passes only when:

- all seven stable IDs remain available to existing presets and content packs;
- every effect resolves explicitly on initiative count 20 and defines a bounded measurable area;
- every area has a visible anchor or terrain telegraph, a positioning answer, a finite end condition, and a non-damage interaction;
- Choking Air is floor-bound and ventilatable rather than a generic reaction penalty;
- Pressure Corpses defines finite armed remains, safe neutralization, damage, and CR-scaled target caps;
- Funeral Silence uses an anchored silence zone rather than a noncanonical spellcasting ability check;
- Graveyard Offerings includes a respectful ritual answer;
- Snapping Webs, Broodmother Web, and Dense Webs remain mechanically distinct;
- no blanket Dexterity disadvantage, 24-hour Lair immunity, surprised-target rider, or unbounded persistent region remains;
- all CR projections compile with verified renderer parity.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== content) {
      console.error(`Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterLairGraftEditorialCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(
  `Lair Effects: ${audit.total}; passing: ${audit.passing}; abilities: ${audit.abilityCount}; bundles: ${audit.bundleCount}; scaled: ${audit.scaledCount}; errors: ${audit.errors.length}.`,
);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
