import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { MONSTER_GRAFTS } from "../../features/monster-composer/data/monster-grafts.js";
import { buildMonsterAttackPatternCatalogAudit } from "../../features/monster-composer/model/monster-attack-pattern.js";

const SCRIPT_PATH = fileURLToPath(import.meta.url);
const REPO_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "../..");
const OUTPUT_DIR = path.join(REPO_ROOT, "docs/terrifying-monsters/phase5");
const OUTPUT_JSON = path.join(OUTPUT_DIR, "attack-patterns.generated.json");
const OUTPUT_MD = path.join(OUTPUT_DIR, "attack-patterns.generated.md");
const CHECK_MODE = process.argv.includes("--check");
const STRICT_MODE = process.argv.includes("--strict");

function stableJson(value) { return `${JSON.stringify(value, null, 2)}\n`; }
function percent(value) { return `${Math.round(Number(value || 0) * 1000) / 10}%`; }

function renderMarkdown(audit) {
  const checkpointRows = audit.checkpointSummary.map((row) =>
    `| ${row.targetCr} | ${row.meanOptions} | ${row.bestiaryTarget?.meanOptions ?? "—"} | ${percent(row.multiattackRate)} | ${percent(row.bestiaryTarget?.multiattackRate)} | ${row.medianAttacks} | ${row.bestiaryTarget?.medianAttacks ?? "—"} | ${percent(row.threePlusOptionsRate)} | ${row.calibrationPass ? "pass" : "error"} |`,
  );
  const patternRows = audit.reports.map((report) => {
    const counts = report.snapshots.map((snapshot) => snapshot.authoredAbilityCount).join(" → ");
    const cadence = report.snapshots.map((snapshot) => snapshot.multiattackCount || 1).join(" → ");
    return `| ${report.source} | \`${report.id}\` | ${counts} | ${cadence} | ${report.progression.lowCrAbilityCount} | ${report.progression.apexAbilityCount} | ${report.status} |`;
  });
  return `# Terrifying Monsters — Phase 5.1 CR-Scaled Attack Pattern Audit

**Generated by:** \`scripts/monster/report-monster-attack-patterns.mjs\`  
**Audit version:** \`${audit.version}\`

## Summary

| Metric | Value |
|---|---:|
| Attack Patterns | ${audit.total} |
| Passing patterns | ${audit.passing} |
| Pattern errors | ${audit.error} |
| Catalog errors | ${audit.errors.length} |
| CR checkpoints | ${audit.checkpoints.join(", ")} |

## Bestiary calibration

| CR | Generated options | Bestiary options | Generated Multiattack | Bestiary Multiattack | Generated median attacks | Bestiary median attacks | Generated 3+ options | Status |
|---:|---:|---:|---:|---:|---:|---:|---:|---|
${checkpointRows.join("\n")}

The targets derive from the 503-monster \`Bestiary.csv\` audit. Calibration is distributional: individual patterns may unlock repertoire or cadence earlier or later when that better expresses their tactical identity.

## Pattern progression

Counts are shown for CR ${audit.checkpoints.join(" / CR ")}.

| Source | Pattern | Ability options | Attack cadence | CR 1 options | CR 15 options | Status |
|---|---|---|---|---:|---:|---|
${patternRows.join("\n")}

## Gate

The audit fails when progression bands overlap, reference missing abilities, regress as CR rises, fail runtime compilation, or place the aggregate catalog outside the Bestiary-derived tolerance.
`;
}

function writeOrCheck(filePath, content) {
  if (CHECK_MODE) {
    const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (actual !== content) {
      console.error(`Stale or missing generated report: ${path.relative(REPO_ROOT, filePath)}`);
      return false;
    }
    return true;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
  console.log(`Wrote ${path.relative(REPO_ROOT, filePath)}`);
  return true;
}

const audit = buildMonsterAttackPatternCatalogAudit(MONSTER_GRAFTS);
const jsonOk = writeOrCheck(OUTPUT_JSON, stableJson(audit));
const mdOk = writeOrCheck(OUTPUT_MD, renderMarkdown(audit));
console.log(`Attack Patterns: ${audit.total}; passing: ${audit.passing}; catalog errors: ${audit.errors.length}.`);
if (!jsonOk || !mdOk || (STRICT_MODE && !audit.pass)) process.exitCode = 1;
